import { createHash } from 'node:crypto';
import type pg from 'pg';
import { listarEntidades, obterEntidade } from './registro.js';
import type { Campo, Entidade } from './tipos.js';

export const id = (nome: string) => '"' + nome.replace(/"/g, '""') + '"';
export const tabelaSql = (e: Entidade) => e.tabela.split('.').map(id).join('.');

function nomeObjeto(prefixo: string, ...partes: string[]) {
  const nome = [prefixo, ...partes].join('_').replace(/\./g, '_');
  if (nome.length <= 63) return nome;
  return nome.slice(0, 50) + '_' + createHash('md5').update(nome).digest('hex').slice(0, 12);
}

const literal = (v: unknown) =>
  typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;

export function tipoSql(c: Campo): string {
  switch (c.tipo) {
    case 'texto':
      return `varchar(${c.max ?? 255})`;
    case 'texto_longo':
    case 'segredo':
      return 'text';
    case 'inteiro':
      return 'integer';
    case 'decimal':
      return `numeric(15,${c.casas ?? 4})`;
    case 'moeda':
      return 'numeric(15,2)';
    case 'data':
      return 'date';
    case 'data_hora':
      return 'timestamptz';
    case 'hora':
      return 'time';
    case 'booleano':
      return 'boolean';
    case 'opcao':
      return 'varchar(40)';
    case 'multi_opcao':
      return 'text[]';
    case 'ref':
      return 'bigint';
    case 'cpf':
      return 'varchar(11)';
    case 'cnpj':
      return 'varchar(14)';
    case 'cns':
      return 'varchar(15)';
    case 'cep':
      return 'varchar(8)';
    case 'telefone':
      return 'varchar(11)';
    case 'email':
      return 'varchar(120)';
    case 'cor':
      return 'varchar(9)';
    case 'json':
      return 'jsonb';
    case 'arquivo':
      return 'uuid';
  }
}

const camposFisicos = (e: Entidade) => e.campos.filter((c) => !c.sqlCalculado);

/**
 * Sincroniza o banco com os metadados: cria esquemas, tabelas, colunas, chaves
 * estrangeiras com bloqueio de exclusão (TR 1.1.1.17), índices, gatilhos de
 * auditoria (TR 1.1.1.37) e comentários usados no dicionário de dados (TR 1.1.2.1.13.1).
 * Operação idempotente: não remove nem altera colunas existentes.
 */
export async function sincronizarEsquema(c: pg.PoolClient, log: (m: string) => void = () => {}) {
  const ents = listarEntidades().filter((e) => !e.ddlManual);

  for (const e of ents) {
    const [esquema, tabela] = e.tabela.split('.');
    await c.query(`create schema if not exists ${id(esquema)}`);
    const existe = (
      await c.query(`select 1 from information_schema.tables where table_schema = $1 and table_name = $2`, [esquema, tabela])
    ).rowCount;
    if (!existe) {
      const cols = camposFisicos(e).map((f) => {
        let def = `${id(f.nome)} ${tipoSql(f)}`;
        if (f.padrao !== undefined) def += ` default ${literal(f.padrao)}`;
        if (f.obrigatorio && f.tipo !== 'segredo') def += ' not null';
        return def;
      });
      await c.query(`create table ${tabelaSql(e)} (
        id bigint generated by default as identity primary key,
        ${cols.map((x) => x + ',').join('\n')}
        criado_em timestamptz not null default now(),
        criado_por bigint,
        atualizado_em timestamptz,
        atualizado_por bigint
      )`);
      log(`tabela criada: ${e.tabela}`);
    } else {
      const atuais = new Map(
        (
          await c.query(
            `select column_name, character_maximum_length from information_schema.columns where table_schema = $1 and table_name = $2`,
            [esquema, tabela],
          )
        ).rows.map((r) => [r.column_name as string, r.character_maximum_length as number | null]),
      );
      for (const f of camposFisicos(e)) {
        if (!atuais.has(f.nome)) {
          const def = `${tipoSql(f)}${f.padrao !== undefined ? ` default ${literal(f.padrao)}` : ''}`;
          await c.query(`alter table ${tabelaSql(e)} add column ${id(f.nome)} ${def}`);
          log(`coluna criada: ${e.tabela}.${f.nome}`);
        } else if (f.tipo === 'texto' && (atuais.get(f.nome) ?? 0) < (f.max ?? 255)) {
          // Ampliação de tamanho é segura e não perde dados.
          await c.query(`alter table ${tabelaSql(e)} alter column ${id(f.nome)} type ${tipoSql(f)}`);
          log(`coluna ampliada: ${e.tabela}.${f.nome}`);
        }
      }
    }

    await c.query(`comment on table ${tabelaSql(e)} is ${literal(e.titulo + (e.descricao ? ' - ' + e.descricao : ''))}`);
    for (const f of camposFisicos(e)) {
      const desc = f.rotulo + (f.opcoes ? ' (' + f.opcoes.map(([v, r]) => `${v}=${r}`).join('; ') + ')' : '');
      await c.query(`comment on column ${tabelaSql(e)}.${id(f.nome)} is ${literal(desc)}`);
    }

    for (const f of camposFisicos(e)) {
      if (f.tipo === 'opcao' && f.opcoes) {
        const nome = nomeObjeto('ck', e.tabela, f.nome);
        await c.query(`alter table ${tabelaSql(e)} drop constraint if exists ${id(nome)}`);
        await c.query(
          `alter table ${tabelaSql(e)} add constraint ${id(nome)} check (${id(f.nome)} in (${f.opcoes
            .map(([v]) => literal(v))
            .join(',')}))`,
        );
      }
      if (f.unico) {
        await c.query(
          `create unique index if not exists ${id(nomeObjeto('ux', e.tabela, f.nome))} on ${tabelaSql(e)} (${id(f.nome)})`,
        );
      }
      if (f.busca && (f.tipo === 'texto' || f.tipo === 'texto_longo')) {
        await c.query(
          `create index if not exists ${id(nomeObjeto('ix', e.tabela, f.nome, 'trgm'))} on ${tabelaSql(e)} using gin (f_unaccent(${id(f.nome)}) gin_trgm_ops)`,
        );
      }
    }
    for (const u of e.unicos ?? []) {
      await c.query(
        `create unique index if not exists ${id(nomeObjeto('ux', e.tabela, ...u))} on ${tabelaSql(e)} (${u.map(id).join(',')})`,
      );
    }

    await c.query(`drop trigger if exists tg_auditoria on ${tabelaSql(e)}`);
    await c.query(
      `create trigger tg_auditoria after insert or update or delete on ${tabelaSql(e)} for each row execute function aud.fn_auditar()`,
    );
    await c.query(`drop trigger if exists tg_carimbo on ${tabelaSql(e)}`);
    await c.query(
      `create trigger tg_carimbo before insert or update on ${tabelaSql(e)} for each row execute function sis.fn_carimbo()`,
    );
  }

  // Chaves estrangeiras após todas as tabelas existirem.
  for (const e of ents) {

    for (const f of camposFisicos(e)) {
      let destino: string | undefined;
      if (f.tipo === 'ref') {
        const alvo = obterEntidade(f.ref!);
        if (!alvo) throw new Error(`Referência inexistente: ${e.nome}.${f.nome} -> ${f.ref}`);
        destino = tabelaSql(alvo) + '(id)';
      } else if (f.tipo === 'arquivo') {
        destino = 'sis.arquivo(id)';
      }
      if (!destino) continue;
      const nome = nomeObjeto('fk', e.tabela, f.nome);
      const ja = (await c.query(`select 1 from pg_constraint where conname = $1`, [nome])).rowCount;
      if (!ja) {
        await c.query(
          `alter table ${tabelaSql(e)} add constraint ${id(nome)} foreign key (${id(f.nome)}) references ${destino} on delete restrict`,
        );
      }
      await c.query(`create index if not exists ${id(nomeObjeto('ix', e.tabela, f.nome))} on ${tabelaSql(e)} (${id(f.nome)})`);
    }
  }
}
